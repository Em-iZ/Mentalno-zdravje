create extension if not exists pgcrypto;
create table if not exists public.admin_users (user_id uuid primary key references auth.users(id) on delete cascade);
create table if not exists public.profiles (user_id uuid primary key references auth.users(id) on delete cascade, nickname text not null check (char_length(nickname) between 1 and 30), created_at timestamptz not null default now());
create unique index if not exists profiles_nickname_unique on public.profiles (lower(nickname));
create table if not exists public.chats (id uuid primary key default gen_random_uuid(), user_id uuid not null unique references auth.users(id) on delete cascade, title text not null default 'Moj pogovor', created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create table if not exists public.messages (id bigint generated by default as identity primary key, chat_id uuid not null references public.chats(id) on delete cascade, user_id uuid not null references auth.users(id) on delete cascade, role text not null check (role in ('user','assistant')), content text not null check (char_length(content) <= 5000), created_at timestamptz not null default now());
create table if not exists public.group_messages (id bigint generated by default as identity primary key, user_id uuid not null references auth.users(id) on delete cascade, role text not null check (role in ('user','assistant')), content text not null check (char_length(content) <= 5000), created_at timestamptz not null default now());
create table if not exists public.ideas (id bigint generated by default as identity primary key, user_id uuid references auth.users(id) on delete set null, nickname text not null check (char_length(nickname) between 1 and 30), idea text not null check (char_length(idea) between 1 and 1000), created_at timestamptz not null default now());

alter table public.admin_users enable row level security;
alter table public.profiles enable row level security;
alter table public.chats enable row level security;
alter table public.messages enable row level security;
alter table public.ideas enable row level security;
alter table public.group_messages enable row level security;

create or replace function public.is_admin() returns boolean language sql security definer set search_path=public stable as $ select exists(select 1 from public.admin_users where user_id=auth.uid()); $;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

