create policy "users read own profile" on public.profiles for select to authenticated using (user_id=auth.uid());
create policy "users create own profile" on public.profiles for insert to authenticated with check (user_id=auth.uid());
create policy "users update own profile" on public.profiles for update to authenticated using (user_id=auth.uid()) with check (user_id=auth.uid());

create policy "users read own chats" on public.chats for select to authenticated using (user_id=auth.uid());
create policy "users create own chats" on public.chats for insert to authenticated with check (user_id=auth.uid());
create policy "users update own chats" on public.chats for update to authenticated using (user_id=auth.uid()) with check (user_id=auth.uid());

create policy "users read own messages" on public.messages for select to authenticated using (exists (select 1 from public.chats c where c.id=chat_id and c.user_id=auth.uid()));
create policy "users create own messages" on public.messages for insert to authenticated with check (user_id=auth.uid() and role='user');
create policy "users delete own messages" on public.messages for delete to authenticated using (user_id=auth.uid());

create policy "users submit ideas" on public.ideas for insert to authenticated with check (user_id=auth.uid());
create policy "admins read ideas" on public.ideas for select to authenticated using (public.is_admin());
create policy "admins delete ideas" on public.ideas for delete to authenticated using (public.is_admin());

create policy "users read group messages" on public.group_messages for select to authenticated using (true);
create policy "users create group messages" on public.group_messages for insert to authenticated with check (user_id=auth.uid() and role='user');
create policy "admins read group messages" on public.group_messages for select to authenticated using (public.is_admin());
create policy "admins create group messages" on public.group_messages for insert to authenticated with check (public.is_admin() and user_id=auth.uid() and role='assistant');

